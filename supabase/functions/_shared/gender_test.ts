import { assertEquals } from 'jsr:@std/assert@1';
import { heuristicGender } from './gender.ts';

const cases: [string, string][] = [
  // Прізвище на -евич/-ич не робить дівчинку хлопцем: по батькові — лише третє слово.
  ["Федкевич Софія В'ячеславівна", 'girl'],
  ['Лінкевич Тетяна', 'girl'],
  ['Мількевич Артем', 'boy'],
  ['Ткаліч Тетяна Валентинівна', 'girl'],
  // Без по батькові — за ім'ям (раніше лишались «не визначено»).
  ['Шостак Аліна', 'girl'],
  ['Гальченко Юрій', 'boy'],
  ['Бойчук Нікіта', 'boy'],
  ['Пелих Нікіта', 'boy'],
  ['Лящук Максим', 'boy'],
  ['Безулий Єлісей', 'boy'],
  ['Кандур Матвій', 'boy'],
  ['Ковалевський Марія', 'girl'],
  ['Грінберг Марина', 'girl'],
  ['Жук Аріна', 'girl'],
  ["Остап'як Яніна", 'girl'],
  ['Сущенко Діана', 'girl'],
  ['Микита', 'boy'],
  ['Микита Іван', 'boy'],
  ['Коваль Ілля', 'boy'],
  ['Петренко Лука', 'boy'],
  ['Сидоренко Любов', 'girl'],
  ['Мельник Анна-Марія', 'girl'],
  // По батькові переважає.
  ['Бараниченко Анастасія Вікторовна', 'girl'],
  ['Бабаш Анатолій Володимирович', 'boy'],
  ['Скалич Любомир Назарійович', 'boy'],
  // Порядок «Ім'я Прізвище».
  ['Аліна Шостак', 'girl'],
  ['Максим Коваленко', 'boy'],
  // Прізвище-ім'я + рідкісне ім'я: стать дає ім'я, а не прізвище.
  ['Марко Абігейла', 'girl'],
  ['Богдан Кіра Русланівна', 'girl'],
  // Апострофи різних видів.
  ['Тарасенко Мар’ян', 'boy'],
  ['Берднікова Дарʼя', 'girl'],
  // Пестливі / порожні.
  ['Коваль Саша', 'unknown'],
  ['', 'unknown'],
];

Deno.test('heuristicGender', () => {
  for (const [name, want] of cases) assertEquals(heuristicGender(name), want, name);
});
