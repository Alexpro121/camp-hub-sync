/**
 * Визначення статі дитини за ПІБ без мережі. Порядок доказів:
 * по батькові (лише третє слово — бо «Федкевич», «Лінкевич» теж закінчуються на -евич),
 * відоме ім'я (будь-яке місце, тож «Аліна Шостак» теж працює), закінчення імені, закінчення прізвища.
 * 'unknown' — коли доказів немає; тоді можна спитати ШІ або виставити вручну.
 */
export type Gender = 'boy' | 'girl' | 'unknown';

