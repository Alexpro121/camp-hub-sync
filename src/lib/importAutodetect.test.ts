import { describe, expect, it, vi } from 'vitest';
vi.mock('@/integrations/supabase/client', () => ({ supabase: { functions: { invoke: async () => ({ data: null, error: { message: 'off' } }) } } }));
import { analyzeMatrix } from '@/lib/importAnalyze';
import { localHeaderMap } from '@/lib/importer';

const brief = (r: { rows: { team_number: number; full_name: string; phone: string | null; is_present: boolean }[] }) =>
  r.rows.map((x) => `${x.team_number}|${x.full_name}|${x.phone ?? ''}|${x.is_present ? '+' : '-'}`);

describe('автодетект: заголовки', () => {
  it('помилки друку, латинські «двійники», крапки та регістр', () => {
    const m = localHeaderMap(['П.І.Б.', 'Телефн', 'Прisутність', 'Номер загону']);
    expect(m['П.І.Б.']).toBe('full_name');
    expect(m['Телефн']).toBe('phone');
    expect(m['Прisутність']).toBe('is_present');
    expect(m['Номер загону']).toBe('team_number');
  });
  it('нові синоніми: прізвище, ім’я, по батькові; контакти; особливості', () => {
    const m = localHeaderMap(["Прізвище, ім'я, по батькові", 'Контактний телефон', 'Особливості', '№ п/п']);
    expect(Object.values(m).sort()).toEqual(['full_name', 'note_from_table', 'phone', 'row_number']);
  });
});

describe('автодетект: за вмістом колонок', () => {
  it('таблиця БЕЗ заголовків: перший рядок лишається дитиною', async () => {
    const r = await analyzeMatrix([
      [1, 'Іваненко Олексій', 1, '0671234567', 'так'],
      [2, 'Коваль Марія', 1, '0501234567', ''],
      [3, 'Бойко Андрій', 2, '0931112233', 'так'],
      [4, 'Мельник Оксана', 2, '', ''],
    ]);
    expect(brief(r)).toEqual([
      '1|Іваненко Олексій|+380671234567|+',
      '1|Коваль Марія|+380501234567|-',
      '2|Бойко Андрій|+380931112233|+',
      '2|Мельник Оксана||-',
    ]);
  });

  it('нерозпізнані заголовки («Хто», «Контакт», «Гр.»): колонки визначаються за вмістом', async () => {
    const r = await analyzeMatrix([
      ['Col A', 'Col B', 'Col C'],
      ['Іваненко Олексій', '0671234567', 3],
      ['Коваль Марія', '0501234567', 3],
      ['Бойко Андрій', '0931112233', 4],
      ['Мельник Оксана', '0991112233', 4],
    ]);
    expect(brief(r).map((x) => x.split('|').slice(0, 3).join('|'))).toEqual([
      '3|Іваненко Олексій|+380671234567', '3|Коваль Марія|+380501234567', '4|Бойко Андрій|+380931112233', '4|Мельник Оксана|+380991112233',
    ]);
  });

  it('колонка команди розпізнається за вмістом, а порядкові номери не стають командою', async () => {
    const r = await analyzeMatrix([
      ['', 'ПІБ', ''],
      [1, 'Іваненко Олексій', 5], [2, 'Коваль Марія', 5], [3, 'Бойко Андрій', 6], [4, 'Мельник Оксана', 6], [5, 'Шевченко Іван', 6],
    ]);
    expect(r.rows.map((x) => x.team_number)).toEqual([5, 5, 6, 6, 6]);
  });

  it('назви заголовків з кількох рядків: заголовок не на першому рядку, є титул', async () => {
    const r = await analyzeMatrix([
      ['Реєстр учасників зміни «Вересень»', '', ''],
      ['Дата формування: 01.09', '', ''],
      ['Прізвище, ім\'я', 'Мобільний', 'Загін'],
      ['Іваненко Олексій', '0671234567', 1],
      ['Коваль Марія', '', 1],
    ]);
    expect(r.rows).toHaveLength(2);
    expect(r.rows[0].team_number).toBe(1);
  });
});

describe('автодетект: різні формати', () => {
  it('команди поруч (блоки колонок із підписами «Команда N»)', async () => {
    const r = await analyzeMatrix([
      ['Команда 1', '', 'Команда 2', ''],
      ['Іваненко Олексій', '0671234567', 'Бойко Андрій', '0931112233'],
      ['Коваль Марія', '', 'Мельник Оксана', ''],
    ]);
    expect(r.rows.map((x) => `${x.team_number}|${x.full_name}`)).toEqual([
      '1|Іваненко Олексій', '1|Коваль Марія', '2|Бойко Андрій', '2|Мельник Оксана',
    ]);
  });

  it('російськомовні заголовки', async () => {
    const r = await analyzeMatrix([
      ['ФИО', 'Отряд', 'Телефон', 'Присутствие'],
      ['Иванов Алексей', 2, '0671234567', 'да'],
      ['Петрова Мария', 2, '', 'нет'],
    ]);
    expect(brief(r)).toEqual(['2|Иванов Алексей|+380671234567|+', '2|Петрова Мария||-']);
  });
});
